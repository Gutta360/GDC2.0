CREATE TABLE medicines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    medicine_id VARCHAR(30) NOT NULL,
    medicine_name VARCHAR(150) NOT NULL,
    available_quantity INTEGER NOT NULL DEFAULT 0,
    expiry_date DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_medicines PRIMARY KEY (id),
    CONSTRAINT uk_medicines_medicine_id UNIQUE (medicine_id),
    CONSTRAINT chk_medicines_available_quantity CHECK (available_quantity >= 0)
);

CREATE UNIQUE INDEX uk_medicines_active_normalized_name
    ON medicines (LOWER(BTRIM(medicine_name)))
    WHERE is_active = TRUE;

CREATE INDEX idx_medicines_active_expiry_name
    ON medicines (is_active, expiry_date, medicine_name);

CREATE TABLE treatments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    treatment_id VARCHAR(30) NOT NULL,
    patient_id BIGINT NOT NULL,
    treatment_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    treatment_type VARCHAR(20) NOT NULL,
    treatment_amount NUMERIC(10, 2) NOT NULL,
    doctor_notes VARCHAR(2000),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by VARCHAR(100),
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by VARCHAR(100),
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_treatments PRIMARY KEY (id),
    CONSTRAINT uk_treatments_treatment_id UNIQUE (treatment_id),
    CONSTRAINT fk_treatments_patient FOREIGN KEY (patient_id)
        REFERENCES patients (id),
    CONSTRAINT chk_treatments_type CHECK (treatment_type IN ('ADVISED', 'DESIRED')),
    CONSTRAINT chk_treatments_amount CHECK (treatment_amount >= 0.00)
);

CREATE INDEX idx_treatments_patient_active_date
    ON treatments (patient_id, is_active, treatment_date DESC, id DESC);

