CREATE TABLE clinical_problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    treatment_id BIGINT,
    follow_up_id BIGINT,
    problem_type VARCHAR(40) NOT NULL,
    notes VARCHAR(2000),
    impaction_type VARCHAR(40),

    CONSTRAINT pk_clinical_problems PRIMARY KEY (id),
    CONSTRAINT fk_clinical_problems_treatment FOREIGN KEY (treatment_id)
        REFERENCES treatments (id),
    CONSTRAINT fk_clinical_problems_follow_up FOREIGN KEY (follow_up_id)
        REFERENCES follow_ups (id),
    CONSTRAINT chk_clinical_problems_owner CHECK (
        (treatment_id IS NOT NULL AND follow_up_id IS NULL)
        OR (treatment_id IS NULL AND follow_up_id IS NOT NULL)
    ),
    CONSTRAINT chk_clinical_problems_type CHECK (
        problem_type IN (
            'ROOT_CANAL',
            'IMPLANTS',
            'IMPACTION',
            'CROWNS_BRIDGES',
            'BRACES',
            'DENTURES',
            'EXTRACTION',
            'FILLING',
            'SCALING',
            'CERVICAL_ABRASION',
            'GENERALIZED_GINGIVITIS'
        )
    ),
    CONSTRAINT chk_clinical_problems_impaction_type CHECK (
        impaction_type IS NULL
        OR impaction_type IN ('MESIO_ANGULAR', 'DISTO_ANGULAR', 'VERTICAL', 'HORIZONTAL')
    )
);

CREATE INDEX idx_clinical_problems_treatment
    ON clinical_problems (treatment_id);

CREATE INDEX idx_clinical_problems_follow_up
    ON clinical_problems (follow_up_id);

CREATE TABLE clinical_problem_teeth (
