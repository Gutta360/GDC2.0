CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    payment_id VARCHAR(30) NOT NULL,
    patient_id BIGINT NOT NULL,
    treatment_id BIGINT NOT NULL,
    payment_mode VARCHAR(20) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    details VARCHAR(1000),
    paid_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT pk_payments PRIMARY KEY (id),
    CONSTRAINT uk_payments_payment_id UNIQUE (payment_id),
    CONSTRAINT uk_payments_treatment_id UNIQUE (treatment_id),
    CONSTRAINT fk_payments_patient FOREIGN KEY (patient_id)
        REFERENCES patients (id),
    CONSTRAINT fk_payments_treatment FOREIGN KEY (treatment_id)
        REFERENCES treatments (id),
    CONSTRAINT chk_payments_mode CHECK (payment_mode IN ('CASH', 'UPI')),
    CONSTRAINT chk_payments_amount CHECK (amount >= 0.00)
);

CREATE INDEX idx_payments_patient_paid_at
    ON payments (patient_id, paid_at DESC, id DESC);
