CREATE SEQUENCE IF NOT EXISTS medicine_number_seq
    START WITH 1
    INCREMENT BY 1;

CREATE SEQUENCE IF NOT EXISTS pharmacy_payment_number_seq
    START WITH 1
    INCREMENT BY 1;

